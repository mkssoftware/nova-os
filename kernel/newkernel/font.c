int font_register(uint32_t id, uint32_t flags, uint32_t size_px) {
    if (font_count >= FONT_CAPACITY) {
        return -1;
    }
    font_record_t *rec = &font_table[font_count];
    rec->id = id;
    rec->flags = flags;
    rec->size_px = size_px;

    if (flags & FONT_FLAG_BITMAP) {
        rec->glyph_w = FONT_SYS_GLYPH_W;
        rec->glyph_h = FONT_SYS_GLYPH_H;
        rec->data_ptr = &font_bitmap_data[0][0];
        rec->data_len = FONT_SYS_CHAR_COUNT * FONT_SYS_BYTES_PER;
        rec->glyph_count = FONT_SYS_CHAR_COUNT;
    }
    rec->fallback_id = 0xFFFFFFFFu;
    rec->provenance = FONT_PROV_EMBEDDED;

    /* Pruefsumme (vereinfachte XOR, NPSPEC-FONT-SECURITY-0001). */
    uint32_t checksum = 0;
    const uint8_t *p = &font_bitmap_data[0][0];
    for (uint32_t i = 0; i < FONT_SYS_CHAR_COUNT * FONT_SYS_BYTES_PER; ++i) {
        checksum ^= p[i];
    }
    rec->checksum = checksum;
    rec->flags |= FONT_FLAG_VERIFIED;

    ++font_count;
    return 0;
}

void font_manager_initialize(void) {
    for (uint32_t i = 0; i < FONT_CAPACITY; ++i) {
        font_table[i] = (font_record_t){0};
    }
    font_count = 0;
    font_active_id = 0;

    font_register(0, FONT_FLAG_MONO | FONT_FLAG_BITMAP | FONT_FLAG_SYSTEM, FONT_SYS_GLYPH_H);

    font_ready = 1;
}

int font_get_glyph(uint32_t codepoint, uint32_t font_id, const uint8_t **out_glyph) {
    (void)font_id;
    if (codepoint >= FONT_SYS_FIRST_CHAR && codepoint <= FONT_SYS_LAST_CHAR) {
        *out_glyph = font_bitmap_data[codepoint - FONT_SYS_FIRST_CHAR];
        return 0;
    }
    /* Fallback: Replacement-Glyph (Leerzeichen). */
    *out_glyph = font_bitmap_data[0];
    return -1;
}

int font_set_fallback(uint32_t font_id, uint32_t fallback_id) {
    for (uint32_t i = 0; i < font_count; ++i) {
        if (font_table[i].id == font_id) {
            font_table[i].fallback_id = fallback_id;
            return 0;
        }
    }
    return -1;
}

int font_set_axis(uint32_t font_id, uint32_t axis_id, uint8_t value) {
    if (axis_id >= FONT_AXIS_COUNT) {
        return -1;
    }
    for (uint32_t i = 0; i < font_count; ++i) {
        if (font_table[i].id == font_id) {
            font_table[i].axes[axis_id] = value;
            return 0;
        }
    }
    return -1;
}

int font_manager_self_test(void) {
    if (font_ready != 1) return -1;
    if (font_count == 0) return -1;

    const uint8_t *glyph = 0;
    if (font_get_glyph(0x41u, 0, &glyph) != 0) return -1; /* 'A' */

    /* Fallback-Lookup: Emoji (U+1F600), ausserhalb des Bereichs - Fehler
       (CF=1 im alten ASM) ist hier der erwartete Erfolgsfall. */
    font_get_glyph(0x1F600u, 0, &glyph);

    return 0;
}
